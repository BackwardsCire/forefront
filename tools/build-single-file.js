#!/usr/bin/env node
/**
 * Build forefront.html — the whole application as one file.
 *
 * Why this exists, given that "no build step" is one of this project's stated
 * rules: the rule is that the app must never REQUIRE a build to run, and it
 * still does not. Open the folder's index.html and everything works, exactly
 * as before. This produces an optional second artifact for one specific
 * situation, which turns out to be the most common one:
 *
 *   A locked-down work laptop. No Node, no Python, no permission to install
 *   either, and no interest in explaining a folder of HTML to IT. One file you
 *   can keep in OneDrive, double-click, and bookmark.
 *
 * The inlining is mechanical — two stylesheets and eleven scripts, in the
 * order index.html already lists them. Nothing is minified, mangled or
 * transformed, so the built file stays as readable as the sources and a stack
 * trace still names the right code.
 *
 * Execution order is preserved for a slightly subtle reason: `defer` is
 * ignored on an inline script, so these run immediately, in document order,
 * during parsing. Since they sit at the end of <body> in dependency order that
 * is equivalent to what deferred external scripts did — and app.js still sees
 * readyState === 'loading' and waits for DOMContentLoaded, exactly as before.
 *
 *   node tools/build-single-file.js          # write forefront.html
 *   node tools/build-single-file.js --check  # fail if it is out of date
 */
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const OUT = path.join(root, 'forefront.html');

/**
 * A closing tag inside the text it is being wrapped in would end the element
 * early and turn the rest of the application into page content. Nothing in
 * this codebase does that today; if something ever does, this stops the build
 * rather than shipping a file that is silently broken halfway down.
 */
function assertNoClosingTag(text, tag, where) {
  const needle = '</' + tag;
  const at = text.toLowerCase().indexOf(needle);
  if (at !== -1) {
    const line = text.slice(0, at).split('\n').length;
    throw new Error(
      `${where}:${line} contains "${needle}", which would close the <${tag}> ` +
      `element it is being inlined into. Escape it (for example "<\\/${tag}") ` +
      `before building.`
    );
  }
}

function build() {
  let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');

  // ---- Stylesheets ----
  html = html.replace(/[ \t]*<link rel="stylesheet" href="([^"]+)">\n?/g, (match, href) => {
    const css = fs.readFileSync(path.join(root, href), 'utf8');
    assertNoClosingTag(css, 'style', href);
    return `  <style>\n/* ===== ${href} ===== */\n${css.trimEnd()}\n  </style>\n`;
  });

  // ---- Scripts ----
  html = html.replace(/[ \t]*<script defer src="([^"]+)"><\/script>\n?/g, (match, src) => {
    const js = fs.readFileSync(path.join(root, src), 'utf8');
    assertNoClosingTag(js, 'script', src);
    return `  <script>\n// ===== ${src} =====\n${js.trimEnd()}\n  </script>\n`;
  });

  if (/<link rel="stylesheet"|<script defer src=/.test(html)) {
    throw new Error('index.html has an external reference this builder did not recognise. ' +
                    'Teach it that shape rather than shipping a file with a broken link.');
  }

  // A note for whoever opens the built file in an editor and wonders where the
  // comments about editing it went.
  const banner = `<!--
  Forefront — the entire application in one file.

  GENERATED by tools/build-single-file.js. Do not edit this file; edit the
  sources in css/ and js/ and build it again. It is byte-identical to opening
  index.html from the full folder, with the two stylesheets and eleven scripts
  inlined in place.

  No build step is needed to RUN Forefront — the folder works as it is. This
  file exists for machines where you cannot install anything and would rather
  keep one file in a synced folder than a directory of them.

  Everything still runs locally in your browser. It makes no network requests
  of any kind and sends nothing anywhere.
-->
`;

  return banner + html;
}

// ---- Run ----

if (require.main === module) {
  const check = process.argv.includes('--check');
  let built;

  try {
    built = build();
  } catch (e) {
    console.error('Build failed: ' + e.message);
    process.exit(1);
  }

  if (check) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
    if (current === built) {
      console.log('forefront.html is up to date (' + (built.length / 1024).toFixed(0) + ' KB)');
      process.exit(0);
    }
    console.error(current === null
      ? 'forefront.html is missing. Run: node tools/build-single-file.js'
      : 'forefront.html is out of date. Run: node tools/build-single-file.js');
    process.exit(1);
  }

  fs.writeFileSync(OUT, built);
  console.log('Wrote forefront.html — ' + (built.length / 1024).toFixed(0) + ' KB, ' +
              built.split('\n').length.toLocaleString() + ' lines, 0 external references');
}

module.exports = { build, OUT };
